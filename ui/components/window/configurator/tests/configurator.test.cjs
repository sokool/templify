const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const Window = require('../../window.js');
const Settings = require('../../../../../app/storage/settings.js');
const { createWindowFixture, pointer } = require('../../../../testing/window-fixture.cjs');

test('Window tool exposes scroll/resize switches, persists behaviour and shows manual width without exporting it', () => {
  const { document, element } = createWindowFixture(), settings = Settings.create(), fields = [];
  const Field = { mount(host, options) {
    const control = document.createElement('input');
    control.value = String(options.attrs?.value ?? '');
    host.append(control);
    const field = { control, options, sync() {}, destroy() { control.remove(); } };
    fields.push(field);
    return field;
  } };
  const context = {};
  vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../configurator.js'), 'utf8'), context);
  const component = Window.mount(element);
  const tool = context.DesignSystemWindowTool.mount(element, { component, settings: settings.scope('components.window'), Field });
  const scroll = fields.find(field => field.options.label === 'Lock page scroll');
  const resize = fields.find(field => field.options.label === 'Allow manual resize');
  assert.equal(scroll.options.attrs.checked, true);
  assert.equal(resize.options.attrs.checked, true);
  scroll.options.onChange({ value: false });
  component.open();
  assert.equal(component.element.modal, false);
  assert.equal(settings.get('components.window.lockScroll'), false);
  const grip = component.element.querySelector('.ds-window-resize');
  pointer(grip, 'pointerdown', 100, 100);
  pointer(grip, 'pointermove', 200, 150);
  pointer(grip, 'pointerup', 200, 150);
  const width = fields.find(field => field.options.label === 'Width (px)');
  assert.equal(width.control.value, '440');
  assert.equal(settings.get('components.window.width'), 480, 'manual resize does not replace default configuration');
  resize.options.onChange({ value: false });
  assert.equal(grip.hidden, true);
  assert.equal(settings.get('components.window.resizable'), false);
  width.options.onChange({ value: '900' });
  assert.equal(component.getSize().width, 900);
  width.options.onChange({ value: 'bad' });
  assert.equal(component.getSize().width, 900);
  tool.destroy();
  assert.equal(component.element.listeners.get('focusin').size, 0);
  component.destroy();
});
