/* Build a file:// compatible catalogue from shared and component colour roles. */
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const roles = JSON.parse(fs.readFileSync(path.join(root, 'colours/colour-roles.json'), 'utf8'))
  .map((role) => ({ ...role, owners: ['Foundation'] }));

for (const name of fs.readdirSync(path.join(root, 'components')).sort()) {
  const file = path.join(root, 'components', name, 'manifest.json');
  if (!fs.existsSync(file)) continue;
  const manifest = JSON.parse(fs.readFileSync(file, 'utf8'));
  for (const role of manifest.colourRoles || []) {
    if (!/^[a-z][a-zA-Z0-9]*$/.test(role.id) || !/^--ds-colour-[a-z-]+$/.test(role.css) ||
      !['brand', 'accent', 'greys'].includes(role.category)) {
      throw Error('Invalid colour role in ' + name);
    }
    const existing = roles.find((entry) => entry.id === role.id);
    if (existing) {
      if (existing.css !== role.css) throw Error('Conflicting role ' + role.id);
      existing.owners.push(name);
    } else {
      roles.push({ ...role, owners: [name] });
    }
  }
}
fs.writeFileSync(path.join(root, 'colours/colour-roles.js'),
  '/* Generated by ui/scripts/build-colour-roles.cjs. Edit colour-roles.json or component manifests. */\n' +
  '(function(root){const roles=' + JSON.stringify(roles, null, 2) +
  ';if(typeof module==="object"&&module.exports)module.exports=roles;else root.DesignSystemColourRoles=roles;})(globalThis);\n');
