/* Build a file:// compatible role catalogue from foundation and opt-in component declarations. */
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),roles=JSON.parse(fs.readFileSync(path.join(__dirname,'colour-roles.json'))).map(role=>({...role,owners:['Foundation']}));
for(const name of fs.readdirSync(path.join(root,'components')).sort()){
 const file=path.join(root,'components',name,'manifest.json');if(!fs.existsSync(file))continue;
 const manifest=JSON.parse(fs.readFileSync(file));for(const role of manifest.colourRoles||[]){
  if(!/^[a-z][a-zA-Z0-9]*$/.test(role.id)||!/^--ds-colour-[a-z-]+$/.test(role.css)||!['brand','accent','greys'].includes(role.category))throw Error('Invalid colour role in '+name);
  const existing=roles.find(entry=>entry.id===role.id);
  if(existing){if(existing.css!==role.css)throw Error('Conflicting role '+role.id);existing.owners.push(name);}
  else roles.push({...role,owners:[name]});
 }
}
fs.writeFileSync(path.join(__dirname,'colour-roles.js'),'/* Generated by build-colour-roles.cjs. Edit colour-roles.json or component manifests. */\n(function(root){const roles='+JSON.stringify(roles,null,2)+';if(typeof module==="object"&&module.exports)module.exports=roles;else root.DesignSystemColourRoles=roles;})(globalThis);\n');
